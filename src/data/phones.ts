export type Format = 'livre' | 'clapet' | 'tri-pliant';
export type BrandSlug = 'samsung' | 'apple' | 'google' | 'motorola' | 'honor' | 'huawei' | 'xiaomi';
export type Status = 'disponible' | 'precommande' | 'fin-de-serie';

export interface Scores {
  ecran: number;
  performances: number;
  photo: number;
  autonomie: number;
  portabilite: number;
  prix: number;
}

